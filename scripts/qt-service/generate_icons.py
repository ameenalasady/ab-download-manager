#!/usr/bin/env python3
"""Deterministically reuse the repository's existing Apache-2.0 Compose icon paths.
No external assets. Fails on unrecognized path operations instead of approximating.
"""
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
NAMES = ('Folder', 'FolderFinished', 'FolderUnfinished', 'Queue', 'FileZip',
         'FileApplication', 'FileVideo', 'FileMusic', 'FilePicture', 'FileDocument')
COMMANDS = dict(moveTo='M', lineTo='L', curveTo='C', horizontalLineTo='H', verticalLineTo='V', close='Z')
paths = {}
for name in NAMES:
    source = ROOT / 'shared/resources/src/commonMain/kotlin/com/abdownloadmanager/resources/icons' / (name + '.kt')
    text = source.read_text()
    assert 'viewportWidth = 24f' in text
    paths[name] = []
    for style, body in re.findall(r'            path\((.*?)\)\s*\{(.*?)\n            \}', text, re.S):
        commands = re.findall(r'^                (\w+)\(([^\n]*)\)$', body, re.M)
        assert commands, name
        path = []
        for operation, arguments in commands:
            assert operation in COMMANDS, (name, operation)
            arguments = arguments.replace('f', '').replace(',', ' ')
            assert re.fullmatch(r'[\d.\-\s]*', arguments), (name, arguments)
            path.append(COMMANDS[operation] + arguments)
        stroked = 'strokeLineWidth = 2f' in style
        assert stroked or 'fill = SolidColor(Color.White)' in style, (name, style)
        paths[name].append(dict(d=' '.join(path), stroked=stroked, evenOdd='PathFillType.EvenOdd' in style))
    assert paths[name], name
out = ROOT / 'desktop/qt-ui/qml/LegacyPaths.js'
content = ('// Generated by scripts/qt-service/generate_icons.py from repository icons; Apache-2.0.\n'
           '.pragma library\nvar paths = ' + json.dumps(paths, indent=4) + '\n')
if sys.argv[1:] == ['--check']:
    assert out.read_text() == content, 'Generated icons are stale; run without --check'
else:
    assert not sys.argv[1:], 'Only --check is supported'
    out.write_text(content)
